@dataclass
class WorldGenome:
    ai_capability: float = 0.78
    compute_demand: float = 0.85
    gdp_growth: float = 0.42
    manufacturing_activity: float = 0.56
    energy_price_pressure: float = 0.82
    energy_supply_stability: float = 0.48
    logistics_flow: float = 0.51
    social_cohesion: float = 0.55
    geopolitical_risk: float = 0.79
    climate_stress: float = 0.38
    cyber_threat_level: float = 0.61
    market_risk_premium: float = 0.68
    supply_chain_stress: float = 0.64
    monetary_tightness: float = 0.72
    information_entropy: float = 0.59
    scientific_frontier_open: float = 0.88
    ai_proof_capacity: float = 0.82
    human_verification_lag: float = 0.71
    mathematical_certainty: float = 0.46
    proof_trust_chain: float = 0.52
    math_community_stability: float = 0.48
    bounty_program_openness: float = 0.72
    responsible_disclosure_strength: float = 0.68
    ai_agent_risk: float = 0.74
    prompt_injection_pressure: float = 0.69
    supply_chain_vuln_discovery: float = 0.71
    proof_verification_backlog: float = 0.71
    trust_chain_friction: float = 0.58
    bounty_spam_noise: float = 0.63
    high_value_vuln_scarcity: float = 0.57


class EvolutionWorld:
    def __init__(self, genome: Optional[WorldGenome] = None):
        self.genome = genome or WorldGenome()
        self.timestep = 0
        self.phase = "STRESSED"
        self.civilization_health = 0.62
        self.resilience_R = 0.58
        self.entropy_S = 0.47
        self.ai_autonomy_U = 0.71
        self.stability_index = 0.55
        self.cascade_risk = 0.43
        self.infrastructure_status = {
            "power_grid": "NORMAL",
            "ai_compute": "HIGH_LOAD",
            "cloud_services": "NORMAL",
            "telecom": "NORMAL",
            "manufacturing": "NORMAL",
            "logistics": "STRESSED",
            "financial_markets": "CAUTIOUS",
            "healthcare": "NORMAL",
            "government": "NORMAL",
        }
        self.shocks_active = []

    def step(self, delta: float = 0.01):
        g = self.genome
        g.cyber_threat_level = clamp(
            g.cyber_threat_level + delta * (g.ai_agent_risk - 0.5) * 0.3
        )
        g.trust_chain_friction = clamp(
            g.trust_chain_friction
            + delta * (1.0 - g.mathematical_certainty) * 0.25
            + delta * (g.proof_verification_backlog - 0.5) * 0.15
        )
        g.bounty_spam_noise = clamp(
            g.bounty_spam_noise
            + delta * (g.ai_proof_capacity - 0.6) * 0.2
            - delta * (g.responsible_disclosure_strength - 0.5) * 0.1
        )
        g.responsible_disclosure_strength = clamp(
            g.responsible_disclosure_strength
            + delta * (g.bounty_program_openness - 0.5) * 0.15
            - delta * g.bounty_spam_noise * 0.1
        )
        g.supply_chain_vuln_discovery = clamp(
            g.supply_chain_vuln_discovery
            + delta * g.ai_proof_capacity * 0.2
            + delta * g.ai_capability * 0.1
        )
        g.mathematical_certainty = clamp(
            g.mathematical_certainty
            - delta * g.proof_verification_backlog * 0.1
            + delta * g.math_community_stability * 0.05
        )
        g.ai_agent_risk = clamp(
            g.ai_agent_risk
            + delta * (g.ai_capability - 0.6) * 0.15
            - delta * g.responsible_disclosure_strength * 0.05
        )
        g.cascade_risk = clamp(
            0.3 * g.geopolitical_risk
            + 0.2 * g.energy_price_pressure
            + 0.15 * g.cyber_threat_level
            + 0.15 * g.trust_chain_friction
            + 0.1 * g.supply_chain_stress
            + 0.1 * g.monetary_tightness
        )
        self.civilization_health = clamp(
            1.0
            - 0.25 * g.geopolitical_risk
            - 0.20 * g.energy_price_pressure
            - 0.15 * g.cascade_risk
            - 0.10 * g.trust_chain_friction
            - 0.10 * g.monetary_tightness
            + 0.10 * g.resilience_R
            + 0.05 * g.responsible_disclosure_strength
        )
        self.stability_index = clamp(
            1.0 - self.cascade_risk - 0.3 * g.information_entropy
        )
        self.timestep += 1
        self._update_phase()

    def _update_phase(self):
        ch = self.civilization_health
        cr = self.cascade_risk
        if ch < 0.35 or cr > 0.75:
            self.phase = "CRISIS"
        elif ch < 0.55 or cr > 0.55:
            self.phase = "STRESSED"
        elif ch > 0.75 and cr < 0.3:
            self.phase = "THRIVING"
        else:
            self.phase = "STABLE"


class FitnessEngine:
    def calculate(self, world: EvolutionWorld, simulation_steps: int = 200) -> float:
        w = copy.deepcopy(world)
        for _ in range(simulation_steps):
            w.step(delta=0.005)
        score = (
            0.30 * w.civilization_health
            + 0.15 * w.stability_index
            + 0.10 * (1.0 - w.cascade_risk)
            + 0.10 * w.genome.responsible_disclosure_strength
            + 0.10 * (1.0 - w.genome.trust_chain_friction)
            + 0.08 * w.genome.supply_chain_vuln_discovery
            + 0.07 * (1.0 - w.genome.bounty_spam_noise)
            + 0.05 * w.genome.mathematical_certainty
            + 0.05 * (1.0 - w.genome.ai_agent_risk)
        )
        return round(score, 6)


class MutationEngine:
    def mutate(self, genome: WorldGenome, rate: float = 0.15) -> WorldGenome:
        g = copy.deepcopy(genome)
        for attr, val in vars(g).items():
            if isinstance(val, (int, float)):
                if random.random() < rate:
                    delta = random.gauss(0, 0.08)
                    setattr(g, attr, clamp(val + delta))
        return g


def clamp(v: float, lo: float = 0.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, float(v)))


