STATE_FILE = "world_state_20261002_complete.json"
OUTPUT_FILE = "jae_bounty_simulation_20261002.json"
STEPS = 200


def load_state(path: str) -> dict:
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        print(f"[WARN] 未找到 {path}，将使用内置 2026-10-02 默认状态。")
        return {}


def inject_state(genome: WorldGenome, state: dict) -> WorldGenome:
    dims = state.get("dimensions", {})
    for key in vars(genome):
        if key in dims:
            setattr(genome, key, float(dims[key]))
    return genome


def inject_world(world: EvolutionWorld, state: dict):
    for key in ["phase", "civilization_health", "resilience_R", "entropy_S",
                "ai_autonomy_U", "stability_index", "cascade_risk", "timestep"]:
        if key in state and hasattr(world, key):
            setattr(world, key, state[key])
    if "infrastructure_status" in state:
        world.infrastructure_status.update(state["infrastructure_status"])
    if "shocks_active" in state:
        world.shocks_active = state["shocks_active"]


